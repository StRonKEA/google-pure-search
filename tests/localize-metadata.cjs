const fs=require('node:fs');
const en='Hides AI features in Google Search and restores available original titles and snippets of automatically translated results.';
const tr='Google aramasında AI alanlarını gizler; otomatik çevrilen başlık ve özetlerin mevcut orijinallerini gösterir.';
const file='clean-google-search.user.js';
const before=fs.readFileSync(file,'utf8');
const marker='// ==/UserScript==';
const pos=before.indexOf(marker);
const lines=before.slice(0,pos).split(String.fromCharCode(10));
const header=lines.flatMap(l=>l.startsWith('// @name ')?['// @name         Google Pure Search','// @name:tr      Google Pure Search — Sade Arama']:l.startsWith('// @description ')?['// @description  '+en,'// @description:tr '+tr]:[l]).join(String.fromCharCode(10));
fs.writeFileSync(file,header+before.slice(pos));
const gen='tests/update-metadata.cjs';
let g=fs.readFileSync(gen,'utf8');
g=g.replace("'// @name         Google Sade Arama',","'// @name         Google Pure Search',"+String.fromCharCode(10)+"  '// @name:tr      Google Pure Search — Sade Arama',");
g=g.replace("'// @description  Google aramasında AI alanlarını gizler ve mevcut orijinal başlık/özetleri gösterir.',",JSON.stringify('// @description  '+en)+','+String.fromCharCode(10)+JSON.stringify('// @description:tr '+tr)+',');
fs.writeFileSync(gen,g);
console.log('Localized metadata updated; runtime preserved.');
